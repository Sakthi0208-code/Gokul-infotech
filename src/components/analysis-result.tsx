"use client";

import { useEffect, useRef, useState } from "react";
import type { Sentiment, TicketAnalysis } from "@/types/ticket";
import { PriorityBadge } from "./priority-badge";

const SENTIMENT_STYLES: Record<Sentiment, string> = {
  Positive: "text-emerald-800",
  Neutral: "text-slate-700",
  Negative: "text-red-700",
};

export function AnalysisResult({ analysis, model }: { analysis: TicketAnalysis; model?: string }) {
  return (
    <article aria-labelledby="analysis-heading" className="flex flex-col gap-5">
      <div className="flex flex-wrap items-baseline justify-between gap-2">
        <h2 id="analysis-heading" className="text-lg font-semibold text-slate-900">
          Analysis
        </h2>
        {model && <p className="text-xs text-slate-500">Generated by {model} · review before sending</p>}
      </div>

      <dl className="grid grid-cols-1 gap-3 sm:grid-cols-3">
        <Stat label="Category">
          <span className="font-semibold text-slate-900">{analysis.category}</span>
        </Stat>
        <Stat label="Priority">
          <PriorityBadge priority={analysis.priority} />
        </Stat>
        <Stat label="Sentiment">
          <span className={`font-semibold ${SENTIMENT_STYLES[analysis.sentiment]}`}>{analysis.sentiment}</span>
        </Stat>
      </dl>

      <Section title="Summary">
        <p>{analysis.summary}</p>
      </Section>

      <Section title="Why this priority">
        <p>{analysis.priority_reason}</p>
      </Section>

      <Section title="Recommended next action">
        <p>{analysis.recommended_action}</p>
      </Section>

      <Section title="Suggested reply" action={<CopyButton text={analysis.suggested_reply} />}>
        <p className="whitespace-pre-wrap rounded-lg border border-slate-200 bg-slate-50 p-4">
          {analysis.suggested_reply}
        </p>
      </Section>
    </article>
  );
}

function Stat({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-1.5 rounded-lg border border-slate-200 bg-white p-3.5">
      <dt className="text-xs font-medium uppercase tracking-wide text-slate-500">{label}</dt>
      <dd className="text-[15px]">{children}</dd>
    </div>
  );
}

function Section({
  title,
  action,
  children,
}: {
  title: string;
  action?: React.ReactNode;
  children: React.ReactNode;
}) {
  return (
    <section className="flex flex-col gap-2">
      <div className="flex items-center justify-between gap-2">
        <h3 className="text-sm font-semibold text-slate-900">{title}</h3>
        {action}
      </div>
      <div className="text-[15px] leading-relaxed text-slate-700">{children}</div>
    </section>
  );
}

type CopyState = "idle" | "copied" | "failed";

function CopyButton({ text }: { text: string }) {
  const [state, setState] = useState<CopyState>("idle");
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => () => {
    if (timer.current) clearTimeout(timer.current);
  }, []);

  async function copy() {
    try {
      if (!navigator.clipboard) throw new Error("Clipboard unavailable");
      await navigator.clipboard.writeText(text);
      setState("copied");
    } catch {
      setState("failed");
    }
    if (timer.current) clearTimeout(timer.current);
    timer.current = setTimeout(() => setState("idle"), 2500);
  }

  const label = state === "copied" ? "Copied!" : state === "failed" ? "Copy failed – select the text manually" : "Copy reply";

  return (
    <>
      <button
        type="button"
        onClick={copy}
        className={`rounded-md border px-2.5 py-1 text-xs font-semibold transition-colors focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-emerald-700 ${
          state === "copied"
            ? "border-emerald-600 bg-emerald-50 text-emerald-800"
            : state === "failed"
              ? "border-red-600 bg-red-50 text-red-700"
              : "border-slate-300 bg-white text-slate-700 hover:bg-slate-50"
        }`}
      >
        {label}
      </button>
      <span role="status" aria-live="polite" className="sr-only">
        {state === "copied" ? "Reply copied to clipboard" : state === "failed" ? "Could not copy the reply" : ""}
      </span>
    </>
  );
}
